//! Fixed IDE exports selected through the desktop's native Save As dialog.
use super::project::LabProject;
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::{
    io::{self, Write},
    path::{Path, PathBuf},
    sync::atomic::{AtomicBool, Ordering},
};

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
pub(super) struct SaveRequest {
    pub format: Format,
    pub project: LabProject,
}

#[derive(Clone, Copy, Deserialize)]
#[serde(rename_all = "lowercase")]
pub(super) enum Format {
    Vscode,
    Clion,
    Gdb,
}

#[derive(Debug, Serialize)]
#[serde(tag = "status", rename_all = "lowercase")]
pub(super) enum Outcome {
    Saved { path: PathBuf },
    Cancelled,
}

pub(super) struct Document {
    name: &'static str,
    description: &'static str,
    extension: &'static str,
    text: String,
}

fn xml(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

impl Document {
    /// The preview is generated by LabProject::ide_config, never supplied by HTTP.
    pub fn from_preview(format: Format, preview: &Value) -> Self {
        let (name, description, extension, text) = match format {
            Format::Vscode => (
                "launch.json",
                "VS Code 调试配置",
                "json",
                serde_json::to_string_pretty(&preview["vscode"]).expect("IDE preview is JSON")
                    + "\n",
            ),
            Format::Gdb => (
                "attach.gdb",
                "GDB 命令文件",
                "gdb",
                preview["gdb"].as_str().expect("GDB preview").into(),
            ),
            Format::Clion => {
                let target = xml(preview["clion"]["target"].as_str().expect("CLion target"));
                let symbols = xml(&preview["clion"]["symbol_file"]
                    .as_str()
                    .expect("CLion symbols")
                    .replace('\\', "/"));
                (
                    "DM-MC02.run.xml",
                    "CLion 运行配置",
                    "xml",
                    format!(
                        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
<component name=\"ProjectRunConfigurationManager\">\n\
  <configuration default=\"false\" name=\"DM-MC02\" type=\"CLion_Remote\" factoryName=\"Remote Debug\" version=\"1\" remoteCommand=\"{target}\" symbolFile=\"{symbols}\" sysroot=\"\">\n\
    <debugger kind=\"GDB\" isBundled=\"true\" />\n\
    <method v=\"2\" />\n\
  </configuration>\n\
</component>\n"
                    ),
                )
            }
        };
        Self {
            name,
            description,
            extension,
            text,
        }
    }

    pub fn save_native(self, cancelled: &AtomicBool) -> io::Result<Outcome> {
        self.save_with(cancelled, |document| {
            rfd::FileDialog::new()
                .set_title("导出 IDE 配置")
                .set_file_name(document.name)
                .add_filter(document.description, &[document.extension])
                .save_file()
        })
    }

    fn save_with(
        &self,
        cancelled: &AtomicBool,
        choose: impl FnOnce(&Self) -> Option<PathBuf>,
    ) -> io::Result<Outcome> {
        if cancelled.load(Ordering::Acquire) {
            return Ok(Outcome::Cancelled);
        }
        let Some(path) = choose(self) else {
            return Ok(Outcome::Cancelled);
        };
        if cancelled.load(Ordering::Acquire) {
            return Ok(Outcome::Cancelled);
        }
        write_selected(&path, self.text.as_bytes())?;
        Ok(Outcome::Saved { path })
    }
}

fn write_selected(path: &Path, contents: &[u8]) -> io::Result<()> {
    let parent = path
        .parent()
        .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidInput, "保存位置需要包含目录"))?;
    // Commit only after the complete configuration has been written and synced.
    let mut temporary = tempfile::NamedTempFile::new_in(parent)?;
    temporary.write_all(contents)?;
    temporary.as_file().sync_all()?;
    temporary.persist(path).map_err(|error| error.error)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    fn preview() -> Value {
        LabProject {
            firmware: Some(r#"C:\local board\symbols & "debug".elf"#.into()),
            gdb_port: Some(4321),
            ..Default::default()
        }
        .ide_config()
        .unwrap()
    }

    #[test]
    fn fixed_formats_preserve_debug_target_and_escape_symbol_paths() {
        let preview = preview();
        let vscode = Document::from_preview(Format::Vscode, &preview);
        assert_eq!(vscode.name, "launch.json");
        let value: Value = serde_json::from_str(&vscode.text).unwrap();
        assert_eq!(value, preview["vscode"]);
        let clion = Document::from_preview(Format::Clion, &preview);
        assert_eq!(clion.name, "DM-MC02.run.xml");
        assert!(clion.text.contains("type=\"CLion_Remote\""));
        assert!(clion.text.contains("remoteCommand=\"127.0.0.1:4321\""));
        assert!(clion
            .text
            .contains("symbolFile=\"C:/local board/symbols &amp; &quot;debug&quot;.elf\""));
        assert!(clion
            .text
            .contains("<debugger kind=\"GDB\" isBundled=\"true\" />"));
        let gdb = Document::from_preview(Format::Gdb, &preview);
        assert_eq!(gdb.name, "attach.gdb");
        assert_eq!(gdb.text, preview["gdb"]);
    }

    #[test]
    fn requests_cannot_supply_arbitrary_content_or_output_paths() {
        let project = serde_json::to_value(LabProject::default()).unwrap();
        for value in [
            serde_json::json!({"format":"vscode", "project":project, "path":"a.json"}),
            serde_json::json!({"format":"clion", "project":project, "text":"arbitrary"}),
            serde_json::json!({"format":"other", "project":project}),
        ] {
            assert!(serde_json::from_value::<SaveRequest>(value).is_err());
        }
    }

    #[test]
    fn native_selection_atomically_replaces_only_the_chosen_file() {
        let directory = tempfile::tempdir().unwrap();
        let destination = directory.path().join("launch.json");
        std::fs::write(&destination, b"existing configuration").unwrap();
        let document = Document::from_preview(Format::Vscode, &preview());
        let outcome = document
            .save_with(&AtomicBool::new(false), |_| Some(destination.clone()))
            .unwrap();
        assert!(matches!(outcome, Outcome::Saved { path } if path == destination));
        assert_eq!(
            std::fs::read_to_string(&destination).unwrap(),
            document.text
        );
    }

    #[test]
    fn cancel_and_shutdown_leave_existing_configuration_untouched() {
        let directory = tempfile::tempdir().unwrap();
        let destination = directory.path().join("launch.json");
        std::fs::write(&destination, b"existing configuration").unwrap();
        let document = Document::from_preview(Format::Vscode, &preview());
        assert!(matches!(
            document
                .save_with(&AtomicBool::new(false), |_| None)
                .unwrap(),
            Outcome::Cancelled
        ));
        let cancelled = AtomicBool::new(false);
        assert!(matches!(
            document
                .save_with(&cancelled, |_| {
                    cancelled.store(true, Ordering::Release);
                    Some(destination.clone())
                })
                .unwrap(),
            Outcome::Cancelled
        ));
        assert_eq!(
            std::fs::read(&destination).unwrap(),
            b"existing configuration"
        );
    }

    #[test]
    fn failed_save_reports_error_and_removes_its_temporary_file() {
        let directory = tempfile::tempdir().unwrap();
        let destination = directory.path().join("existing-directory");
        std::fs::create_dir(&destination).unwrap();
        let preserved = destination.join("keep.txt");
        std::fs::write(&preserved, b"keep").unwrap();
        let document = Document::from_preview(Format::Clion, &preview());
        assert!(document
            .save_with(&AtomicBool::new(false), |_| Some(destination))
            .is_err());
        assert_eq!(std::fs::read(&preserved).unwrap(), b"keep");
        assert_eq!(std::fs::read_dir(directory.path()).unwrap().count(), 1);
    }
}
